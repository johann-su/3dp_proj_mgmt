import { test } from "node:test";
import assert from "node:assert/strict";
import { creatorFallback, parseFileCreator } from "@/lib/file-creator";

const model = (...meta: [string, string][]) =>
  `<?xml version="1.0"?><model unit="millimeter">${meta
    .map(([name, value]) => `<metadata name="${name}">${value}</metadata>`)
    .join("")}<resources><object id="1">`;

test("parseFileCreator reads Bambu Studio and PrusaSlicer from Application", () => {
  assert.deepEqual(parseFileCreator(model(["Application", "BambuStudio-02.08.02.61"])), {
    app: "Bambu Studio",
    version: "02.08.02.61",
  });
  // PrusaSlicer writes other metadata first; order doesn't matter.
  assert.deepEqual(
    parseFileCreator(model(["slic3rpe:Version3mf", "1"], ["Application", "PrusaSlicer-2.9.2"])),
    { app: "PrusaSlicer", version: "2.9.2" },
  );
  // Unknown apps pass through by name.
  assert.deepEqual(parseFileCreator(model(["Application", "Cura 5.7.1"])), {
    app: "Cura",
    version: "5.7.1",
  });
});

// OrcaSlicer saves Application = BambuStudio-<compat version> for
// compatibility; its own metadata entry is what identifies it.
test("parseFileCreator identifies OrcaSlicer despite its Bambu Application tag", () => {
  assert.deepEqual(
    parseFileCreator(model(["Application", "BambuStudio-02.06.00.51"], ["OrcaSlicer", "2.4.2"])),
    { app: "OrcaSlicer", version: "2.4.2" },
  );
});

test("parseFileCreator falls back to PrusaSlicer's config header", () => {
  assert.deepEqual(
    parseFileCreator(model(), "; generated by PrusaSlicer 2.9.0 on 2026-10-15 at 12:00:00 UTC\nlayer_height = 0.2"),
    { app: "PrusaSlicer", version: "2.9.0" },
  );
});

test("parseFileCreator returns null when the file doesn't say (CAD exports)", () => {
  assert.equal(parseFileCreator(model()), null);
  assert.equal(parseFileCreator(null), null);
});

test("creatorFallback names Onshape exports and OpenSCAD variants", () => {
  assert.deepEqual(creatorFallback({ onshapeElementId: "e1", generatedFromId: null }), {
    app: "Onshape",
    version: null,
  });
  assert.deepEqual(creatorFallback({ onshapeElementId: null, generatedFromId: "f1" }), {
    app: "OpenSCAD",
    version: null,
  });
  assert.equal(creatorFallback({ onshapeElementId: null, generatedFromId: null }), null);
});
