// Which application created a .3mf ("Bambu Studio 02.08.02.61", "OrcaSlicer
// 2.4.2", "PrusaSlicer 2.9.2", "Onshape"). Stored per model file so slicing
// can later be routed to a matching backend, and existing files backfilled
// (scripts/backfill-file-creator.ts). Not the slicer that produced the
// *estimate* — that's model_files.slice_engine.

export type FileCreator = { app: string; version: string | null };

// Names in 3MF `Application` metadata -> display names. Others pass through.
const APP_NAMES: Record<string, string> = {
  bambustudio: "Bambu Studio",
  orcaslicer: "OrcaSlicer",
  prusaslicer: "PrusaSlicer",
  superslicer: "SuperSlicer",
};

function metadata(xml: string, name: string): string | null {
  const m = xml.match(new RegExp(`<metadata name="${name}">([^<]*)</metadata>`));
  return m?.[1].trim() || null;
}

// "BambuStudio-02.08.02.61" / "PrusaSlicer-2.9.2" / "Cura 5.7.1" -> app + version.
function splitApplication(value: string): FileCreator {
  const m = value.match(/^(.*?)[-_ ]v?(\d[\w.+-]*)$/);
  const name = (m ? m[1] : value).trim();
  return {
    app: APP_NAMES[name.toLowerCase().replace(/\s+/g, "")] ?? name,
    version: m ? m[2] : null,
  };
}

// From the archive's own metadata:
// - `3D/3dmodel.model` (only its head is needed — the <metadata> elements come
//   before the geometry). OrcaSlicer must be checked first: for compatibility
//   it writes `Application = BambuStudio-<compat version>` and adds its own
//   `<metadata name="OrcaSlicer">2.4.2</metadata>`.
// - PrusaSlicer's `Slic3r_PE.config` header ("; generated by PrusaSlicer 2.9.0
//   on …"), for projects whose model file lacks the Application entry.
// Null when the file doesn't say (Onshape and other CAD exports) — see
// creatorFallback.
export function parseFileCreator(
  modelHead: string | null,
  prusaIni: string | null = null,
): FileCreator | null {
  if (modelHead) {
    const orca = metadata(modelHead, "OrcaSlicer");
    if (orca) return { app: "OrcaSlicer", version: orca };
    const application = metadata(modelHead, "Application");
    if (application) return splitApplication(application);
  }
  const generated = prusaIni?.match(/^; generated by (\S+) (\d[\w.+-]*)/m);
  if (generated) {
    return { app: APP_NAMES[generated[1].toLowerCase()] ?? generated[1], version: generated[2] };
  }
  return null;
}

// Files whose archive names no creator still say where they came from: an
// Onshape export (a CAD file without slicer metadata — no printer, plates or
// settings) or an OpenSCAD variant rendered by this instance.
export function creatorFallback(file: {
  onshapeElementId: string | null;
  generatedFromId: string | null;
}): FileCreator | null {
  if (file.onshapeElementId) return { app: "Onshape", version: null };
  if (file.generatedFromId) return { app: "OpenSCAD", version: null };
  return null;
}
